def write_pdf(path: Path, pages: list[str]) -> None:
    doc = pymupdf.open()
    for text in pages:
        page = doc.new_page()
        if page.insert_textbox(pymupdf.Rect(50, 45, 545, 755), text, fontsize=10, lineheight=1.35) < 0:
            raise ValueError(f"Synthetic test page text overflow: {path}")
    path.write_bytes(doc.tobytes())
    doc.close()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--overwrite", action="store_true", help="Overwrite this generator's existing TC01–TC19 outputs; never deletes files.")
    args = parser.parse_args()
    ROOT.mkdir(parents=True, exist_ok=True)
    existing = list(ROOT.iterdir())
    unknown = [item.name for item in existing if item.name != "README.md" and not re.fullmatch(r"TC\d{2}", item.name)]
    if unknown:
        raise SystemExit(f"Refusing to touch unrelated dataset entries: {unknown}")
    if existing and not args.overwrite:
        raise SystemExit(f"Dataset exists; pass --overwrite to rewrite only generated TC01–TC19 files without deleting files: {ROOT}")
    for case in CASES:
        directory = ROOT / case["case_id"]
        directory.mkdir(exist_ok=True)
        source_docs = {}
        expected_docs = {}
        for filename, pages in case["documents"].items():
            source_docs[filename] = {"synthetic": True, "pages": pages}
            if pages is None:
                (directory / filename).write_bytes(b"%PDF-1.7\ncorrupt synthetic fixture\n")
            else:
                write_pdf(directory / filename, pages)
            expected_docs[filename] = case["expected"].get(filename, [])
        (directory / "source.json").write_text(json.dumps({"case_id": case["case_id"], "title": case["title"], "documents": source_docs}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        expected = {"case_id": case["case_id"], "title": case["title"], "expected_by_document": expected_docs,
                    "expected_error": case.get("expected_error"), "expected_amendment_change": case.get("expected_amendment_change")}
        (directory / "expected.json").write_text(json.dumps(expected, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "README.md").write_text(
        "# Synthetic evaluation dataset\n\n"
        f"{len(CASES)} manually authored synthetic cases. Borrowers, terms, thresholds, and clauses are fictional. "
        "Ground truth is stored in each `expected.json`, separate from the extraction implementation and source pages. "
        "No LLM generated the ground truth. Recreate only when the dataset directory is empty with "
        "`python -m app.scripts.create_eval_dataset`. The invalid PDF case intentionally contains corrupt bytes.\n",
        encoding="utf-8",
    )
    print(f"Created {len(CASES)} synthetic cases under {ROOT}")


if __name__ == "__main__":
    main()
