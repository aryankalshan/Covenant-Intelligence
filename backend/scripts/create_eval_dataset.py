def obligation(category, description, wording, page, section, *, threshold=None, operator=None,
               unit=None, basis=None, frequency=None, period=None, deadline=None, deadline_rule=None,
               conditions=None, exceptions=None, definitions=None, references=None, uncertainty=None):
    evidence = [{"quote": wording, "source_page": page, "source_section": section}]
    for definition in definitions or []:
        if definition["definition_text"] and definition["source_page"]:
            evidence.append({"quote": definition["definition_text"], "source_page": definition["source_page"], "source_section": definition.get("source_section")})
    for ref in references or []:
        if ref.get("target_description") and ref.get("target_page"):
            evidence.append({"quote": ref["target_description"], "source_page": ref["target_page"], "source_section": ref.get("target_section")})
    canonical_references = [
        {key: ref.get(key) for key in ("reference_text", "target_description", "source_page", "source_section")}
        for ref in references or []
    ]
    return {
        "obligation_category": category,
        "obligation_description": description,
        "source_wording": wording,
        "threshold_value": threshold,
        "comparison_operator": operator,
        "threshold_unit": unit,
        "measurement_basis": basis,
        "testing_frequency": frequency,
        "testing_period": period,
        "reporting_deadline": deadline,
        "deadline_calculation_rule": deadline_rule,
        "conditions": conditions,
        "exceptions": exceptions,
        "referenced_definitions": definitions,
        "cross_references": canonical_references or None,
        "supporting_evidence": evidence,
        "uncertainty_reasons": uncertainty or [],
    }


def definition(term, text=None, page=None, section=None):
    return {"term": term, "definition_text": text, "source_page": page, "source_section": section}


